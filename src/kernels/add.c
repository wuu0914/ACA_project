#include "ca_kernels.h"

#include <stdint.h>

static int32_t clamp(int32_t value, int32_t low, int32_t high) {
  if (value < low) return low;
  if (value > high) return high;
  return value;
}

/*
 * Math:
 *   real1 = input1_scale * (input1_q - input1_zero_point)
 *   real2 = input2_scale * (input2_q - input2_zero_point)
 *   output_q = clamp(round((real1 + real2) / output_scale) + output_zero_point, activation_min, activation_max)
 *
 * Techniques:
 *   1. Preserve more precision by left-shifting:
 *      L = left_shift (20 for the int8 path)
 *   2. Transform inputs into a new scale for unit alignment: 
 *      common_scale = 2 * max(input1_scale, input2_scale)
 *      input1_real_multiplier = input1_scale / common_scale
 *      input2_real_multiplier = input2_scale / common_scale
 *   3. Transform back to output scale:
 *      output_real_multiplier = common_scale / (2^L * output_scale)
 */
void add_s8(const int8_t *input1, 
            const int8_t *input2, 
            const AddParams *p,
            int8_t *output) {
  for (int i = 0; i < p->size; ++i) {
    // Note: input_offset = -input_zero_point
    const int32_t shifted1 = ((int32_t)input1[i] + p->input1_offset) * (1 << p->left_shift);  // shifted1 = (input1_q - input1_zp) * 2^L
    const int32_t shifted2 = ((int32_t)input2[i] + p->input2_offset) * (1 << p->left_shift);  // shifted2 = (input2_q - input2_zp) * 2^L

    // Note: input_multiplier = input_scale / common_scale
    //       shift is generated by QuantizeMultiplier() in TFLite.
    const int32_t scaled1 = output_scaling_round2(shifted1, p->input1_multiplier, p->input1_shift); // scaled1 ~= round(shifted1 * input1_scale / common_scale)
    const int32_t scaled2 = output_scaling_round2(shifted2, p->input2_multiplier, p->input2_shift); // scaled2 ~= round(shifted2 * input2_scale / common_scale)

    // Note: output_multiplier = common_scale / (2^L * output_scale)
    int32_t sum = output_scaling_round2(scaled1 + scaled2, p->output_multiplier, p->output_shift);  // sum ~= round((scaled1 + scaled2) * common_scale / (2^L * output_scale))
    sum = clamp(sum + p->output_offset, p->activation_min, p->activation_max);
    output[i] = (int8_t)sum;
  }
}
